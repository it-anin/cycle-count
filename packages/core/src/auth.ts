/**
 * การแปลงรหัสพนักงานเป็นอีเมลสำหรับ Supabase Auth
 *
 * พนักงานคลังล็อกอินบน PDA ด้วยรหัสพนักงาน + PIN ไม่ใช่อีเมล
 * (จอ 480px พิมพ์อีเมลลำบาก และพนักงานส่วนใหญ่ไม่มีอีเมลบริษัท)
 * แต่ Supabase Auth ต้องการอีเมล จึงสังเคราะห์ขึ้นมาแบบ deterministic
 *
 * ทั้งหน้าล็อกอินบน PDA และหน้าสร้างผู้ใช้ฝั่งแอดมินต้องเรียกฟังก์ชันนี้ตัวเดียวกัน
 * ไม่งั้นรหัสที่สร้างกับรหัสที่ล็อกอินจะ map ไปคนละอีเมล
 */

/**
 * โดเมนสำหรับอีเมลสังเคราะห์
 *
 * ใช้ subdomain ของโดเมนจริงแทน `.local` เพราะ Supabase Auth ตรวจรูปแบบอีเมล
 * และอาจปฏิเสธ TLD ที่ไม่มีอยู่จริง — โดเมนนี้ไม่มี MX record จึงไม่มีเมลส่งถึงจริงอยู่ดี
 * (สร้างผู้ใช้ด้วย email_confirm: true จึงไม่มีการส่งอีเมลยืนยัน)
 *
 * ⚠ เปลี่ยนค่านี้ = ผู้ใช้เดิมทั้งหมดล็อกอินไม่ได้ เพราะ map ไปคนละอีเมล
 */
export const PDA_AUTH_DOMAIN = 'pda.anin.co.th';

/**
 * `EMP-2041` → `emp2041@pda.anin.local`
 * ตัดทุกอย่างที่ไม่ใช่ a–z 0–9 ออก ให้ `emp-2041`, `EMP 2041`, `emp2041` เข้าบัญชีเดียวกัน
 */
export function authEmailForEmployee(employeeCode: string, domain = PDA_AUTH_DOMAIN): string {
  const slug = employeeCode.trim().toLowerCase().replace(/[^a-z0-9]/g, '');
  if (!slug) throw new Error('รหัสพนักงานต้องมีตัวอักษรหรือตัวเลขอย่างน้อยหนึ่งตัว');
  return `${slug}@${domain}`;
}
